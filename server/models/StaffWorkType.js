const mongoose = require("mongoose");

const staffWorkTypeSchema = new mongoose.Schema(
  {
    shop: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Shop",
      required: true,
      index: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      trim: true,
      default: "",
    },
    active: {
      type: Boolean,
      default: true,
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    isDeleted: {
      type: Boolean,
      default: false,
      index: true,
    },
  },
  { timestamps: true },
);

staffWorkTypeSchema.index({ shop: 1, name: 1 }, { unique: true, partialFilterExpression: { isDeleted: false } });
staffWorkTypeSchema.index({ shop: 1, active: 1, createdAt: -1 });

module.exports = mongoose.model("StaffWorkType", staffWorkTypeSchema);
